CW, CH = 6, 9


def glyph_rows(c):
    if c in LOWER:
        return LOWER[c]
    rows = G.get(c, G['?'])
    return rows + ["     ", "     "]


def build():
    OUT.mkdir(parents=True, exist_ok=True)
    chars = [chr(i) for i in range(32, 127)]
    img = Image.new("RGBA", (16 * CW, 6 * CH), (0, 0, 0, 0))
    for i, c in enumerate(chars):
        ox, oy = (i % 16) * CW, (i // 16) * CH
        for y, row in enumerate(glyph_rows(c)):
            for x, ch in enumerate(row):
                if ch == '#':
                    img.putpixel((ox + x, oy + y), (255, 255, 255, 255))
    img.save(OUT / "font.png")

    # big font: 2x pixels with a darker bottom-right bevel; white so it can be tinted
    BW, BH = CW * 2, CH * 2
    big = Image.new("RGBA", (16 * BW, 6 * BH), (0, 0, 0, 0))
    for i, c in enumerate(chars):
        ox, oy = (i % 16) * BW, (i // 16) * BH
        rows = glyph_rows(c)
        ink = {(x, y) for y, r in enumerate(rows) for x, ch in enumerate(r) if ch == '#'}
        for (x, y) in ink:
            for dy in range(2):
                for dx in range(2):
                    big.putpixel((ox + x * 2 + dx, oy + y * 2 + dy), (255, 255, 255, 255))
        for (x, y) in ink:
            # lower-right edge pixels get the shade tone (grey 150) = bevel
            for dx, dy in ((2, 1), (1, 2), (2, 2)):
                px, py = ox + x * 2 + dx, oy + y * 2 + dy
                if px < ox + BW and py < oy + BH and big.getpixel((px, py))[3] == 0:
                    big.putpixel((px, py), (150, 150, 150, 255))
    big.save(OUT / "font_big.png")
    print("font.png", img.size, "font_big.png", big.size)


if __name__ == "__main__":
    build()
