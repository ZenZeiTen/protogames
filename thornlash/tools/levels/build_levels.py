"""Builds stages 2-6 of Thornlash as ASCII block files (godot/content/levels/stageN.txt).

Stage 1 is hand-written; these are generated from the builder calls below so stair
geometry, landings and gaps are always consistent. The output files are the content the
game ships; this script is their source. All layouts are original.

Legend (see stage1.txt): # stone  = ledge  X breakable  / \\ stairs  ~ water  ^ spikes
  @ start  i/I/j candles  G/M/F spawn zones  E exit  Z boss trigger  letters = enemies
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "godot" / "content" / "levels"


class Block:
    def __init__(self, bid, w, h, **meta):
        self.id, self.w, self.h = bid, w, h
        self.g = [["."] * w for _ in range(h)]
        self.meta = meta
        self.candles = []
        self.hidden = []

    def put(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.g[y][x] = c

    def fill(self, x0, y0, x1, y1, c="#"):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.put(x, y, c)

    def ground(self, x0, x1, top, c="#"):
        """Solid from row `top` down to the bottom of the block."""
        self.fill(x0, top, x1, self.h - 1, c)

    def ledge(self, x0, x1, y, c="="):
        self.fill(x0, y, x1, y, c)

    def stair_up_right(self, x, floor_row, n):
        """'/' from the floor at `floor_row` (row of the floor tiles) rising n steps to the right.
        Returns (landing_x, landing_row): place the landing floor there."""
        for i in range(n):
            self.put(x + i, floor_row - 1 - i, "/")
        return x + n, floor_row - n

    def stair_up_left(self, x, floor_row, n):
        """'\\' whose bottom cell is (x, floor_row-1), rising n steps to the left."""
        for i in range(n):
            self.put(x - i, floor_row - 1 - i, "\\")
        return x - n, floor_row - n

    def clear(self, x0, y0, x1, y1):
        self.fill(x0, y0, x1, y1, ".")

    def candle(self, x, y, drop, kind="j"):
        self.put(x, y, kind)
        self.candles.append((y, x, drop))

    def wall_x(self, x, y, drop="-"):
        self.put(x, y, "X")
        self.hidden.append((y, x, drop))

    def text(self):
        meta = dict(self.meta)
        # candle drops and hidden items are listed in reading order (row, then column)
        # keep only candles and walls that survived later edits (a stair may overwrite one)
        live = [(y, x, d) for (y, x, d) in self.candles if self.g[y][x] in "iIj"]
        walls = [(y, x, d) for (y, x, d) in self.hidden if self.g[y][x] == "X"]
        meta["candles"] = ",".join(d for _, _, d in sorted(live))
        meta["hidden"] = ",".join(d for _, _, d in sorted(walls))
        lines = [f"@block {self.id}"]
        for k, v in meta.items():
            if v != "" and v is not None:
                lines.append(f"{k}={v}")
        lines.append("---")
        lines += ["".join(r) for r in self.g]
        return "\n".join(lines) + "\n"


def write_stage(n, title, blocks):
    head = f"; Stage {n} - {title}. Generated by tools/levels/build_levels.py (original layout).\n\n"
    (OUT / f"stage{n}.txt").write_text(head + "\n".join(b.text() for b in blocks), encoding="utf8", newline="\n")
    print(f"stage{n}: " + ", ".join(f"{b.id} {b.w}x{b.h}" for b in blocks))


# ======================================================================== Stage 2: The Catacombs

def stage2():
    a = Block("2-1", 84, 12, name="Ossuary Gate", title="The Catacombs", area="catacomb", music="stage2",
              time=300, next="2-2")
    a.fill(0, 0, 83, 0)
    a.ground(0, 30, 7)                      # upper floor at row 7 (feet y = 112)
    a.put(2, 6, "@")
    for x, d in ((6, "heart"), (14, "bigheart"), (22, "heart")):
        a.candle(x, 5, d)
    a.put(20, 6, "S")
    # stairs down from the upper floor to the lower hall (row 10)
    a.clear(31, 7, 36, 9)
    a.ground(31, 83, 10)
    lx, lr = a.stair_up_left(36, 10, 3)     # bottom cell (36,9) rising left to landing (33, 7)
    a.put(33, 7, "#")
    a.put(32, 7, "#")
    a.put(31, 7, "#")
    a.put(26, 2, "B")
    a.put(44, 3, "B")
    a.put(50, 9, "S")
    a.put(64, 9, "Q")
    a.candle(42, 7, "whip")
    a.candle(52, 7, "heart")
    a.candle(58, 7, "flask")
    a.candle(70, 7, "bigheart")
    a.put(40, 9, "G")
    a.fill(83, 1, 83, 9)
    a.put(82, 8, "E")
    a.put(82, 9, "E")

    b = Block("2-2", 104, 12, name="Flooded Crypt", area="catacomb", music="stage2", next="2-3")
    b.fill(0, 0, 103, 0)
    b.fill(0, 10, 103, 11, "~")             # black water across the whole crypt floor
    b.ground(0, 9, 8)
    b.put(2, 7, "@")
    # stepping-stone piers with 2-tile gaps
    x = 12
    piers = []
    while x < 92:
        wdt = 3 if (x // 12) % 2 else 4
        b.ground(x, x + wdt - 1, 8)
        piers.append((x, wdt))
        x += wdt + 2
    b.ground(92, 103, 8)
    b.put(20, 10, "F")
    b.put(52, 10, "F")
    b.put(80, 10, "F")
    for i, (px, wdt) in enumerate(piers[::3]):
        b.candle(px + 1, 5, ["heart", "bigheart", "axe", "heart", "bag400", "heart"][i % 6])
    b.put(40, 3, "M")
    b.put(34, 2, "B")
    b.put(70, 2, "B")
    # a raised crypt shelf over the water with a breakable wall hiding a roast
    b.ledge(60, 70, 4)
    b.wall_x(71, 4, "roast")
    b.wall_x(71, 3, "-")
    b.candle(64, 2, "heart")
    b.fill(103, 1, 103, 7)
    b.put(102, 6, "E")
    b.put(102, 7, "E")

    c = Block("2-3", 70, 12, name="Charnel Deep", area="catacomb", music="stage2", next="",
              boss="wyrm", arena=50)
    c.fill(0, 0, 69, 0)
    c.ground(0, 69, 10)
    c.put(2, 9, "@")
    c.fill(10, 8, 14, 9, "%")               # bone-brick tombs to jump over
    c.fill(26, 8, 29, 9, "%")
    c.put(20, 9, "S")
    c.put(36, 9, "K")
    for x, d in ((8, "heart"), (18, "bigheart"), (32, "heart"), (44, "cross"), (55, "heart"), (65, "bigheart")):
        c.candle(x, 7, d)
    c.put(52, 9, "Z")
    return [a, b, c]


# ======================================================================== Stage 3: The Ramparts

def stage3():
    a = Block("3-1", 96, 12, name="Western Rampart", title="The Ramparts", area="rampart", music="stage3",
              time=300, next="3-2")
    a.ground(0, 95, 10)
    a.put(2, 9, "@")
    # crenellated parapet: merlons along the wall edge to hop over
    for x in range(12, 90, 10):
        a.fill(x, 8, x + 1, 9)
    a.clear(38, 10, 40, 11)                 # fallen sections of the wall walk
    a.clear(66, 10, 68, 11)
    for x in (18, 30, 50, 60, 78):
        a.put(x, 3, "R")
    a.put(46, 9, "W")
    a.put(84, 9, "W")
    for i, x in enumerate(range(6, 92, 11)):
        a.candle(x, 6, ["heart", "bigheart", "whip", "heart", "dagger", "bigheart", "heart", "double", "heart"][i % 9], "I")
    a.fill(95, 0, 95, 9)
    a.put(94, 8, "E")
    a.put(94, 9, "E")

    # vertical block: climb the tower by zig-zag stairs
    t = Block("3-2", 22, 36, name="Tower Climb", area="tower", music="stage3", next="3-3")
    t.fill(0, 0, 0, 35)
    t.fill(21, 0, 21, 35)
    t.ground(1, 20, 34)
    t.put(3, 33, "@")
    floor = 34
    x = 4
    right = True
    level = 0
    while floor > 8:
        if right:
            lx, lr = t.stair_up_right(x, floor, 5)
            t.ledge(lx, 20, lr)
            t.candle(15, lr - 2, ["heart", "bigheart", "heart", "potion", "heart"][level % 5])
            x = 16
        else:
            lx, lr = t.stair_up_left(x, floor, 5)
            t.ledge(1, lx, lr)
            t.candle(4, lr - 2, ["heart", "bigheart", "heart", "rosary", "heart"][level % 5])
            x = 5
        floor = lr
        right = not right
        level += 1
    t.put(10, 20, "M")
    t.put(12, 12, "N")
    t.put(10, floor - 1, "E")
    t.put(11, floor - 1, "E")
    t.put(10, floor - 2, "E")

    c = Block("3-3", 72, 12, name="Lantern Bridge", area="rampart", music="stage3", next="",
              boss="warden", arena=52)
    c.ground(0, 71, 10)
    c.put(2, 9, "@")
    c.clear(14, 10, 15, 11)
    c.clear(28, 10, 30, 11)
    c.put(22, 3, "R")
    c.put(36, 9, "K")
    for x, d in ((8, "heart"), (20, "bigheart"), (34, "heart"), (46, "axe"), (58, "heart"), (66, "bigheart")):
        c.candle(x, 6, d, "I")
    c.put(55, 9, "Z")
    return [a, t, c]


