def stage6():
    a = Block("6-1", 100, 12, name="Long Gallery", title="The Throne of Ash", area="throne", music="stage6",
              time=400, next="6-2")
    a.fill(0, 0, 99, 0)
    a.ground(0, 99, 10)
    a.put(2, 9, "@")
    for x in (20, 44, 68):
        a.put(x, 9, "O")
    a.put(30, 9, "P")
    a.put(56, 9, "P")
    a.put(80, 9, "Q")
    a.put(36, 3, "N")
    a.put(74, 3, "N")
    for i, x in enumerate(range(6, 96, 9)):
        a.candle(x, 6, ["heart", "bigheart", "whip", "heart", "axe", "heart", "double", "bigheart", "heart", "roast"][i % 10], "I")
    a.fill(99, 1, 99, 9)
    a.put(98, 8, "E")
    a.put(98, 9, "E")

    b = Block("6-2", 72, 24, name="Stair of Ash", area="throne", music="stage6", next="6-3")
    b.fill(0, 0, 71, 0)
    b.ground(0, 16, 22)
    b.put(2, 21, "@")
